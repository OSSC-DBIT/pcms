const I18nCtx = createContext<{ lang: Lang; t: (k: TKey) => string; setLang: (l: Lang) => void }>({
  lang: 'en', t: (k) => en[k], setLang: () => {},
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('pcms.lang') === 'hi' ? 'hi' : 'en'))
  useEffect(() => {
    localStorage.setItem('pcms.lang', lang)
    document.documentElement.lang = lang
  }, [lang])
  const t = (k: TKey) => (lang === 'hi' ? hi[k] ?? en[k] : en[k])
  return <I18nCtx.Provider value={{ lang, t, setLang: setLangState }}>{children}</I18nCtx.Provider>
}

export const useT = () => useContext(I18nCtx)
